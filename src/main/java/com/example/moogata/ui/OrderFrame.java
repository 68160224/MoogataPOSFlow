    /**
     * โหลดเมนูพร้อมขาย (สถานะ 'มี') จาก MenuService — เมนู 'หมด' ต้องไม่ขึ้น
     */
    private void loadMenu() {
        DefaultTableModel model = (DefaultTableModel) tblMenu.getModel();
        model.setRowCount(0);
        menuItems = menuService.getAvailable();
        for (MenuItem item : menuItems) {
            model.addRow(new Object[]{item.getName(), item.getPriceText(), item.getUnit()});
        }
        tblMenu.getColumnModel().getColumn(0).setPreferredWidth(200);
    }

    /**
     * อ่านรายการจากฐานข้อมูลใหม่ทั้งหมด — ตารางขวาคือภาพจริงของ bill_item ใน db
     */
    private void refreshBill() {
        DefaultTableModel model = (DefaultTableModel) tblBill.getModel();
        model.setRowCount(0);
        List<BillItem> items = billService.getBillItems(bill.getId());
        for (BillItem item : items) {
            model.addRow(new Object[]{item.getItemName(), item.getQty(),
                String.format("%.2f", item.getUnitPrice()), item.getLineTotalText()});
        }
        lblTotal.setText(String.format("%.2f", billService.getTotal(bill.getId())) + " บาท");
    }
