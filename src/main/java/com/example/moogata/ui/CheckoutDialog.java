    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        double cash;
        try {
            cash = Double.parseDouble(txtCash.getText().trim());
        } catch (NumberFormatException ex) {
            cash = 0;
        }
// กฎและการปิดบิลอยู่ที่ BillService.checkout — ตรวจเงินพอ + ปิดบิล + คืนโต๊ะ
        Bill closed = billService.checkout(bill, cash);
        if (closed == null) {
            JOptionPane.showMessageDialog(this, "เงินรับไม่พอ — ตรวจยอดอีกครั้ง",
                    "ชำระเงินไม่สำเร็จ", JOptionPane.ERROR_MESSAGE);
            return;
        }
        saved = true;
        JOptionPane.showMessageDialog(this,
                "ปิดบิลสำเร็จ · ยอด " + String.format("%.2f", closed.getTotal())
                + " บาท · ทอน " + String.format("%.2f", closed.getChangeAmount()) + " บาท\n"
                + "โต๊ะกลับสู่สถานะว่างแล้ว",
                "เช็คบิลสำเร็จ", JOptionPane.INFORMATION_MESSAGE);
        dispose();
    }//GEN-LAST:event_btnConfirmActionPerformed

