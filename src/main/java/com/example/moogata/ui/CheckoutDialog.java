    /**
     * คิดเงินทอนสด ๆ จากช่องกรอก — ทศนิยม 2 ตำแหน่ง (SC-1)
     * กดยืนยันได้เมื่อเงินพอ
     */
    private void updateChange() {
        try {
            double cash = Double.parseDouble(txtCash.getText().trim());
            double total = billService.getTotal(bill.getId());
            if (cash >= total) {
                lblChange.setText(String.format("%.2f บาท", cash - total));
                btnConfirm.setEnabled(true);
                return;
            }
        } catch (NumberFormatException ex) {
            // ยังพิมพ์ไม่จบ / พิมพ์ไม่ใช่ตัวเลข — ปฏิบัติเหมือนยังไม่มีเงินรับ
        }
        lblChange.setText("-");
        btnConfirm.setEnabled(false);
    }
